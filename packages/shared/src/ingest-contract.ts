/**
 * Public ingestion contract between the browser SDK and the API.
 * This file must stay dependency-free (no zod): the SDK bundles it.
 */

export const SITE_KEY_PATTERN = /^ldr_[A-Za-z0-9_-]{20}$/;
export const INGEST_SCHEMA_VERSION = 1;

export const INGEST_LIMITS = {
  maxEventsPerBatch: 25,
  maxBodyBytes: 32 * 1024,
  maxUrlLength: 2048,
  maxNameLength: 64,
  maxProps: 20,
  maxPropKeyLength: 40,
  maxPropValueLength: 200,
  /** Events older than this (client clock) are rejected; newer than now+skew are clamped. */
  maxEventAgeMs: 24 * 3_600_000,
  maxClockSkewMs: 5 * 60_000,
} as const;

export type IngestEventType = 'pageview' | 'event';
export type PropValue = string | number | boolean | null;

export interface IngestEvent {
  /** Client-generated unique id (UUID). Used for server-side de-duplication. */
  id: string;
  type: IngestEventType;
  /** Custom event name; required when type = 'event'. */
  name?: string;
  /** Client epoch milliseconds. */
  ts: number;
  /** Full page URL. The server strips query strings except utm_* parameters. */
  url: string;
  referrer?: string;
  /** Random, first-party, non-identifying ids generated by the SDK. */
  visitorId: string;
  sessionId: string;
  props?: Record<string, PropValue>;
  screen?: { w: number; h: number };
  lang?: string;
}

export interface IngestBatch {
  /** Schema version of this payload. */
  v: number;
  siteKey: string;
  sdkVersion: string;
  /** navigator.webdriver or similar automation signal. */
  automated?: boolean;
  events: IngestEvent[];
}

export interface IngestResponse {
  accepted: number;
  duplicates: number;
  rejected: number;
}

/** Served to the SDK from GET /public/v1/sites/:siteKey/config. Never contains private data. */
export interface PublicSiteConfig {
  schemaVersion: number;
  tracking: {
    enabled: boolean;
    consentRequired: boolean;
    respectDoNotTrack: boolean;
  };
  flushIntervalMs: number;
  maxBatchSize: number;
}
